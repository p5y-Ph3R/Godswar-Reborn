    public static int GetBaseHp(int level, byte profession)
    {
        return HpByLevelAndProfession[LevelIndex(level), ProfessionIndex(profession)];
    }

    public static int GetBaseMp(int level, byte profession)
    {
        return MpByLevelAndProfession[LevelIndex(level), ProfessionIndex(profession)];
    }

    public static int GetTotalHp(GameCharacter character)
    {
        return (int)Math.Min(
            int.MaxValue,
            (long)GetBaseHp(character.Level, character.Profession) +
            Math.Max(0, character.CalculatedStats?.HpRecovery ?? 0));
    }

    public static int GetTotalMp(GameCharacter character)
    {
        return (int)Math.Min(
            int.MaxValue,
            (long)GetBaseMp(character.Level, character.Profession) +
            Math.Max(0, character.CalculatedStats?.MpRecovery ?? 0));
    }

    public static bool TryApply(GameCharacter character)
    {
        lock (character.VitalsSync)
        {
            if (character.CurrentHp <= 0)
            {
                return false;
            }

            var maxHp = Math.Max(1, character.MaxHp);
            var maxMp = Math.Max(0, character.MaxMp);
            var hpRecovery = (long)GetTotalHp(character);
            var mpRecovery = (long)GetTotalMp(character);

            var nextHp = (int)Math.Min(maxHp, character.CurrentHp + hpRecovery);
            var nextMp = (int)Math.Min(maxMp, character.CurrentMp + mpRecovery);
            if (nextHp == character.CurrentHp && nextMp == character.CurrentMp)
            {
                return false;
            }

            character.CurrentHp = nextHp;
            character.CurrentMp = nextMp;
            character.MarkVitalsChanged();
            return true;
        }
    }

    private static int LevelIndex(int level)
    {
        return Math.Clamp(level, 1, MaximumLevel) - 1;
    }

    private static int ProfessionIndex(byte profession)
    {
        return Math.Clamp((int)profession, 0, 3);
    }
}

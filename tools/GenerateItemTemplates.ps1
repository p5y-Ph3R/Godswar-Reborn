param(
    [string]$ClientRoot = "C:\Godswar Origin",
    [string]$CSharpOutputPath = "C:\Reborn\src\Godswar.Server\State\ItemTemplateSeed.Generated.cs",
    [string]$SqlOutputPath = "C:\Reborn\database\postgres\002_item_templates.sql"
)

$ErrorActionPreference = "Stop"

$itemBasePath = Join-Path $ClientRoot "Localization\en_us\Settings\Sys\ItemBaseAttribute.xml"
$equipNamePath = Join-Path $ClientRoot "Localization\en_us\Text\EquipName.dat"

if (-not (Test-Path $itemBasePath)) {
    throw "ItemBaseAttribute.xml not found: $itemBasePath"
}

if (-not (Test-Path $equipNamePath)) {
    throw "EquipName.dat not found: $equipNamePath"
}

function ConvertTo-CSharpString([string]$value) {
    if ($null -eq $value) {
        return 'string.Empty'
    }

    return '"' + $value.Replace('\', '\\').Replace('"', '\"') + '"'
}

function ConvertTo-SqlString([string]$value) {
    if ($null -eq $value) {
        return 'NULL'
    }

    return "'" + $value.Replace("'", "''") + "'"
}

function ConvertTo-NullableIntLiteral([string]$value) {
    if ([string]::IsNullOrWhiteSpace($value)) {
        return 'null'
    }

    return [int]$value
}

function ConvertTo-SqlNullableInt([string]$value) {
    if ([string]::IsNullOrWhiteSpace($value)) {
        return 'NULL'
    }

    return [int]$value
}

function Get-AttributeValue($attributes, [string]$name) {
    if ($attributes.Contains($name)) {
        return $attributes[$name]
    }

    return $null
}

function Get-EquipmentSlot([string]$type) {
    switch ($type) {
        'head' { return 0 }
        'amulet' { return 1 }
        'glove' { return 2 }
        'armor' { return 3 }
        'cloth' { return 3 }
        'cuff' { return 4 }
        'girdle' { return 5 }
        'shoes' { return 6 }
        'leggins' { return 7 }
        'ring' { return 8 }
        'weapon' { return 10 }
        'shield' { return 11 }
        'stylish' { return 12 }
        default { return $null }
    }
}

$equipableTypes = [System.Collections.Generic.HashSet[string]]::new([StringComparer]::OrdinalIgnoreCase)
@(
    'weapon',
    'shield',
    'armor',
    'cloth',
    'head',
    'cuff',
    'leggins',
    'glove',
    'shoes',
    'girdle',
    'amulet',
    'ring',
    'stylish'
) | ForEach-Object { [void]$equipableTypes.Add($_) }

$displayNames = @{}
foreach ($line in Get-Content $equipNamePath) {
    if ([string]::IsNullOrWhiteSpace($line) -or $line.StartsWith('//')) {
        continue
    }

    $parts = $line -split "`t", 2
    if ($parts.Count -eq 2 -and -not [string]::IsNullOrWhiteSpace($parts[0])) {
        $displayNames[$parts[0]] = $parts[1].Trim()
    }
}

[xml]$itemBase = Get-Content $itemBasePath -Raw
$itemNodes = $itemBase.SelectNodes('/ItemBaseAttribute//*[@ID]')
$templates = @(foreach ($node in $itemNodes) {
    $attributes = [ordered]@{}
    foreach ($attribute in $node.Attributes) {
        $attributes[$attribute.Name] = $attribute.Value
    }

    $kind = Get-AttributeValue $attributes 'Type'
    if ([string]::IsNullOrWhiteSpace($kind) -or -not $equipableTypes.Contains($kind)) {
        continue
    }

    $equipmentSlot = Get-EquipmentSlot $kind
    if ($null -eq $equipmentSlot) {
        continue
    }

    $playLevelText = Get-AttributeValue $attributes 'PlayLv'
    if ($null -eq $playLevelText) {
        $playLevelText = ''
    }

    $playLevel = $playLevelText -split ',', 2
    $minLevel = if ($playLevel.Count -ge 1) { $playLevel[0] } else { $null }
    $maxLevel = if ($playLevel.Count -ge 2) { $playLevel[1] } else { $null }
    $classIds = @()
    $classText = Get-AttributeValue $attributes 'Class'
    if (-not [string]::IsNullOrWhiteSpace($classText)) {
        $classIds = $classText.Split(',', [StringSplitOptions]::RemoveEmptyEntries) |
            ForEach-Object { [Int16]$_.Trim() }
    }

    $displayName = $displayNames[$node.Name]
    if ($null -eq $displayName) {
        $displayName = $node.Name
    }

    [pscustomobject]@{
        Id = [int]$attributes['ID']
        Kind = $kind
        NameKey = $node.Name
        DisplayName = $displayName
        EquipmentSlot = [Int16]$equipmentSlot
        ClassIds = [Int16[]]$classIds
        MinLevel = $minLevel
        MaxLevel = $maxLevel
        Hand = Get-AttributeValue $attributes 'Hand'
        SkillFlag = Get-AttributeValue $attributes 'SkillFlag'
        Texture = Get-AttributeValue $attributes 'Texture'
        Icon = Get-AttributeValue $attributes 'Icon'
        StatsJson = ($attributes | ConvertTo-Json -Compress)
    }
}) | Sort-Object Id


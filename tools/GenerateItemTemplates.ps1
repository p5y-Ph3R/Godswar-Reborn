[void]$sql.AppendLine("-- <auto-generated />")
[void]$sql.AppendLine("-- Generated from Godswar Origin Localization/en_us/Settings/Sys/ItemBaseAttribute.xml.")
[void]$sql.AppendLine("CREATE TABLE IF NOT EXISTS item_templates (")
[void]$sql.AppendLine("    id integer PRIMARY KEY,")
[void]$sql.AppendLine("    kind varchar(32) NOT NULL,")
[void]$sql.AppendLine("    name_key varchar(128) NOT NULL,")
[void]$sql.AppendLine("    display_name varchar(255) NOT NULL,")
[void]$sql.AppendLine("    equipment_slot smallint NOT NULL,")
[void]$sql.AppendLine("    class_ids smallint[] NOT NULL DEFAULT '{}',")
[void]$sql.AppendLine("    min_level integer,")
[void]$sql.AppendLine("    max_level integer,")
[void]$sql.AppendLine("    hand smallint,")
[void]$sql.AppendLine("    skill_flag integer,")
[void]$sql.AppendLine("    texture varchar(255) NOT NULL DEFAULT '',")
[void]$sql.AppendLine("    icon varchar(32) NOT NULL DEFAULT '',")
[void]$sql.AppendLine("    stats jsonb NOT NULL DEFAULT '{}'::jsonb")

[void]$sql.AppendLine("CREATE INDEX IF NOT EXISTS ix_item_templates_equipment_slot ON item_templates (equipment_slot);")
[void]$sql.AppendLine("CREATE INDEX IF NOT EXISTS ix_item_templates_class_ids ON item_templates USING gin (class_ids);")
[void]$sql.AppendLine()
[void]$sql.AppendLine("INSERT INTO item_templates (id, kind, name_key, display_name, equipment_slot, class_ids, min_level, max_level, hand, skill_flag, texture, icon, stats)")
[void]$sql.AppendLine("VALUES")

for ($i = 0; $i -lt $templates.Count; $i++) {
    $template = $templates[$i]
    $classIds = if ($template.ClassIds.Count -eq 0) {
        "ARRAY[]::smallint[]"
    } else {
        "ARRAY[" + (($template.ClassIds | ForEach-Object { [Int16]$_ }) -join ",") + "]::smallint[]"
    }

    $suffix = if ($i -eq $templates.Count - 1) { "" } else { "," }
    [void]$sql.AppendLine(
        "    (" +
        "$($template.Id), " +
        "$(ConvertTo-SqlString $template.Kind), " +
        "$(ConvertTo-SqlString $template.NameKey), " +
        "$(ConvertTo-SqlString $template.DisplayName), " +
        "$($template.EquipmentSlot), " +
        "$classIds, " +
        "$(ConvertTo-SqlNullableInt $template.MinLevel), " +
        "$(ConvertTo-SqlNullableInt $template.MaxLevel), " +
        "$(ConvertTo-SqlNullableInt $template.Hand), " +
        "$(ConvertTo-SqlNullableInt $template.SkillFlag), " +
        "$(ConvertTo-SqlString $template.Texture), " +
        "$(ConvertTo-SqlString $template.Icon), " +
        "$(ConvertTo-SqlString $template.StatsJson)::jsonb)" +
        "$suffix")
}

[void]$sql.AppendLine("ON CONFLICT (id) DO UPDATE")
[void]$sql.AppendLine("SET kind = EXCLUDED.kind,")
[void]$sql.AppendLine("    name_key = EXCLUDED.name_key,")
[void]$sql.AppendLine("    display_name = EXCLUDED.display_name,")
[void]$sql.AppendLine("    equipment_slot = EXCLUDED.equipment_slot,")
[void]$sql.AppendLine("    class_ids = EXCLUDED.class_ids,")
[void]$sql.AppendLine("    min_level = EXCLUDED.min_level,")
[void]$sql.AppendLine("    max_level = EXCLUDED.max_level,")

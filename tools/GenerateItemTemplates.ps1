[void]$csharp.AppendLine("    string Kind,")
[void]$csharp.AppendLine("    string NameKey,")
[void]$csharp.AppendLine("    string DisplayName,")
[void]$csharp.AppendLine("    short EquipmentSlot,")
[void]$csharp.AppendLine("    short[] ClassIds,")
[void]$csharp.AppendLine("    int? MinLevel,")
[void]$csharp.AppendLine("    int? MaxLevel,")
[void]$csharp.AppendLine("    short? Hand,")
[void]$csharp.AppendLine("    int? SkillFlag,")
[void]$csharp.AppendLine("    string Texture,")
[void]$csharp.AppendLine("    string Icon,")
[void]$csharp.AppendLine("    string StatsJson);")
[void]$csharp.AppendLine()
[void]$csharp.AppendLine("internal static class ItemTemplateSeeds")
[void]$csharp.AppendLine("{")
[void]$csharp.AppendLine("    public static IReadOnlyList<ItemTemplateSeed> All { get; } =")
[void]$csharp.AppendLine("    [")

foreach ($template in $templates) {
    $classIds = if ($template.ClassIds.Count -eq 0) {
        "[]"
    } else {
        "new short[] { " + (($template.ClassIds | ForEach-Object { $_.ToString() }) -join ", ") + " }"
    }

    [void]$csharp.AppendLine(
        "        new(" +
        "$($template.Id), " +
        "$(ConvertTo-CSharpString $template.Kind), " +
        "$(ConvertTo-CSharpString $template.NameKey), " +
        "$(ConvertTo-CSharpString $template.DisplayName), " +
        "$($template.EquipmentSlot), " +
        "$classIds, " +
        "$(ConvertTo-NullableIntLiteral $template.MinLevel), " +
        "$(ConvertTo-NullableIntLiteral $template.MaxLevel), " +
        "$(ConvertTo-NullableIntLiteral $template.Hand), " +
        "$(ConvertTo-NullableIntLiteral $template.SkillFlag), " +
        "$(ConvertTo-CSharpString $template.Texture), " +
        "$(ConvertTo-CSharpString $template.Icon), " +
        "$(ConvertTo-CSharpString $template.StatsJson)),")
}

[void]$csharp.AppendLine("    ];")
[void]$csharp.AppendLine("}")


    $rawAttributes = [ordered]@{}
    foreach ($attribute in $node.Attributes) {
        $rawAttributes[$attribute.Name] = $attribute.Value
    }

    $levels = @()
    foreach ($attribute in $node.Attributes) {
        if ($attribute.Name -match '^L(\d+)$') {
            $levels += [pscustomobject]@{
                Level = [int]$Matches[1]
                Value = [decimal]::Parse($attribute.Value, $invariantCulture)
            }
        }
    }

    $levelValues = [decimal[]]@(
        $levels |
            Sort-Object Level |
            ForEach-Object { $_.Value }
    )

    $distribution = [Int16[]]@()
    $distributionText = Get-AttributeValue $rawAttributes 'Distribution'
    if (-not [string]::IsNullOrWhiteSpace($distributionText)) {
        $distribution = [Int16[]]@(
            $distributionText.Split(',', [StringSplitOptions]::RemoveEmptyEntries) |
                ForEach-Object { [Int16]$_.Trim() }
        )
    }

    [pscustomobject]@{
        Id = [int](Get-AttributeValue $rawAttributes 'ID')
        NameKey = $node.Name
        StatType = [Int16](Get-AttributeValue $rawAttributes 'Type')
        Distribution = $distribution
        Percent = (Get-AttributeValue $rawAttributes 'Flag') -eq '1'
        MaxLevel = [Int16]($levelValues.Count)
        LevelValues = $levelValues
        StatsJson = ($rawAttributes | ConvertTo-Json -Compress)
    }
}) | Sort-Object Id


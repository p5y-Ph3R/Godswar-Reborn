$invariantCulture = [System.Globalization.CultureInfo]::InvariantCulture

function ConvertTo-CSharpString([string]$value) {
    if ($null -eq $value) {
        return 'string.Empty'
    }

    return '"' + $value.Replace('\', '\\').Replace('"', '\"') + '"'
}

function ConvertTo-SqlString([string]$value) {
    if ($null -eq $value) {
        return 'NULL'
    }

    return "'" + $value.Replace("'", "''") + "'"
}

function ConvertTo-CSharpDecimalLiteral([decimal]$value) {
    return $value.ToString($invariantCulture) + 'm'
}

function ConvertTo-SqlNumericLiteral([decimal]$value) {
    return $value.ToString($invariantCulture)
}

function ConvertTo-SqlSmallintArray([Int16[]]$values) {
    if ($values.Count -eq 0) {
        return "ARRAY[]::smallint[]"
    }

    return "ARRAY[" + (($values | ForEach-Object { $_.ToString($invariantCulture) }) -join ",") + "]::smallint[]"
}

function ConvertTo-SqlNumericArray([decimal[]]$values) {
    if ($values.Count -eq 0) {
        return "ARRAY[]::numeric[]"
    }

    return "ARRAY[" + (($values | ForEach-Object { ConvertTo-SqlNumericLiteral $_ }) -join ",") + "]::numeric[]"
}

function ConvertTo-CSharpSmallintArray([Int16[]]$values) {
    if ($values.Count -eq 0) {
        return "[]"
    }

    return "new short[] { " + (($values | ForEach-Object { $_.ToString($invariantCulture) }) -join ", ") + " }"
}

function ConvertTo-CSharpDecimalArray([decimal[]]$values) {
    if ($values.Count -eq 0) {
        return "[]"
    }

    return "new decimal[] { " + (($values | ForEach-Object { ConvertTo-CSharpDecimalLiteral $_ }) -join ", ") + " }"
}

function Get-AttributeValue($attributes, [string]$name) {
    if ($attributes.Contains($name)) {
        return $attributes[$name]
    }

    return $null
}


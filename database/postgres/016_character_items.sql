    attribute_level2 smallint,
    attribute_level3 smallint,
    attribute_level4 smallint,
    attribute_level5 smallint,
    item_quality smallint NOT NULL DEFAULT 1,
    item_grade smallint NOT NULL DEFAULT 1,
    bound smallint NOT NULL DEFAULT 1,
    stack smallint NOT NULL DEFAULT 1,
    item_exp integer NOT NULL DEFAULT 0,
    holy_suit_code integer NOT NULL DEFAULT 0,
    holy_socket_count smallint NOT NULL DEFAULT 0,
    holy_socket1_effect_id smallint,
    holy_socket1_level smallint,
    holy_socket2_effect_id smallint,

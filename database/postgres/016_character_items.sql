    NULLIF(item_parts[14], '')::smallint,
    NULLIF(item_parts[15], '')::smallint,
    NULLIF(item_parts[16], '')::smallint,
    NULLIF(item_parts[17], '')::smallint,
    COALESCE(NULLIF(item_parts[7], '')::smallint, 1),
    COALESCE(NULLIF(item_parts[8], '')::smallint, 1),
